#include "ft_printf.h"

int	ft_putstr(char *s)
{
	size_t	i;
	long	size;

	i = 0;
	size = ft_strlen(s);
	while (s[i])
	{
		ft_putchar(s[i]);
		i++;
	}
	return (size);
}
