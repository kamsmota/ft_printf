#include "ft_printf.h"

int	ft_putstr(char *s)
{
	size_t	i;

	i = 0;
	if (!s)
		return (ft_putstr("(null)"));
	while (s[i])
	{
		if ((ft_putchar(s[i++]) == -1))
			return (-1);
	}
	return (i);
}
